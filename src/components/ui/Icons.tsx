export const SocialPlatformIcon: React.FC<{ platform?: string; icon?: string; className?: string }> = ({
  platform = '',
  icon = '',
  className = 'w-4 h-4',
}) => {
  const key = (platform || icon).toLowerCase().trim();

  if (key.includes('linkedin')) return <LinkedinIcon className={className} />;
  if (key.includes('github')) return <GithubIcon className={className} />;
  if (key.includes('twitter') || key === 'x' || key.includes('x.com')) return <XIcon className={className} />;
  if (key.includes('instagram')) return <InstagramIcon className={className} />;
  if (key.includes('youtube')) return <YoutubeIcon className={className} />;
  if (key.includes('facebook')) return <FacebookIcon className={className} />;
  if (key.includes('scholar')) return <GoogleScholarIcon className={className} />;
  if (key.includes('researchgate')) return <ResearchGateIcon className={className} />;
  if (key.includes('orcid')) return <OrcidIcon className={className} />;
  if (key.includes('mail') || key.includes('email')) return <MailIcon className={className} />;
  return <GlobeIcon className={className} />;
};
